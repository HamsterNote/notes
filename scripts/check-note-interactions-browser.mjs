import assert from "node:assert/strict"
import { mkdirSync, writeFileSync } from "node:fs"
import { chromium } from "playwright"

const base = process.env.NOTES_DEMO_URL ?? "http://127.0.0.1:9235"
const dir = "evidence/ham257"
mkdirSync(dir, { recursive: true })
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(base)
  const area = page.locator(".hn-editor-content")
  await area.waitFor()
  console.log(`Environment: Linux; Chromium ${browser.version()}; yarn dev demo; automated browser keyboard only, no physical macOS/Windows keyboard`)
  const p = text => ({ type: "paragraph", ...(text ? { content: [{ type: "text", text }] } : {}) })
  const q = (...content) => ({ type: "blockquote", attrs: { author: "张三" }, content })
  let loadId = 0
  const load = async content => {
    const data = await page.evaluate(async content => {
      const { normalizeInitialHnnContent } = await import("/src/lib/hnn/nodeId.ts")
      return normalizeInitialHnnContent({ type: "doc", content })
    }, content)
    await page.locator('input[type=file][accept^=".hnn"]').setInputFiles({
      name: `ham257-${++loadId}.hnn`, mimeType: "application/json",
      buffer: Buffer.from(JSON.stringify({ schemaVersion: 1, data }))
    })
    await page.waitForFunction(id => document.querySelector("#demo-doc-select").selectedOptions[0].textContent.startsWith(`ham257-${id}（`), loadId)
    await area.waitFor()
  }
  const doc = () => area.evaluate(e => e.editor.getJSON())
  const select = (offset, text) => area.evaluate((e, { offset, text }) => {
    let pos
    e.editor.state.doc.descendants((node, at) => { if (pos === undefined && node.isTextblock && (text === undefined || node.textContent === text)) pos = at + 1 + offset })
    e.editor.commands.setTextSelection(pos)
    e.editor.view.focus()
  }, { offset, text })
  const evidence = {}
  await load([q(p("甲乙"))])
  assert.equal(await area.locator("blockquote input, blockquote footer").count(), 0)
  await select(0)
  await page.keyboard.type("改")
  assert.equal((await doc()).content[0].attrs.author, "张三")
  assert((await area.evaluate(e => e.editor.state.doc.textContent)).includes("改甲乙"), JSON.stringify(await doc()))
  await page.getByRole("button", { name: "保存", exact: true }).click()
  await page.locator(".hn-save-status").getByText("已保存", { exact: true }).waitFor()
  await page.getByRole("button", { name: "重新载入", exact: true }).click()
  await area.waitFor()
  assert.equal((await doc()).content[0].attrs.author, "张三")
  assert((await area.evaluate(e => e.editor.state.doc.textContent)).includes("改甲乙"))
  evidence.S1 = await doc()
  console.log("PASS S1: no author UI; edit/save/reload preserves author and body")
  evidence.S2 = []
  for (const offset of [0, 1, 2]) {
    await load([q(p("甲乙"), p("丙"))])
    await select(offset)
    const before = await doc()
    await page.keyboard.press("Enter")
    const result = await doc()
    assert.equal(result.content[offset ? 1 : 0].type, "paragraph")
    assert.equal(await area.evaluate(e => e.editor.state.selection.$from.parentOffset), 0)
    await page.keyboard.press("Control+z")
    assert.deepEqual(await doc(), before)
    await page.keyboard.press("Control+Shift+Z")
    assert.deepEqual(await doc(), result)
    evidence.S2.push(result)
  }
  await load([q(q(p("甲乙")), p("丙"))])
  await select(1)
  await page.keyboard.press("Enter")
  assert.equal((await doc()).content[1].type, "paragraph")
  await load([q(p())])
  await select(0); await page.keyboard.press("Enter")
  assert.equal((await doc()).content[0].type, "paragraph")
  await load([q(p("甲乙"))])
  await select(1); await page.keyboard.press("Shift+Enter")
  assert.equal((await doc()).content[0].content[0].content[1].type, "hardBreak")
  console.log("PASS S2: start/middle/end, nested/empty quote, Shift+Enter; exact single undo/redo")
  await load([q(p("甲乙"), p("丙")), p("后继")])
  const initial = await doc()
  const openDelete = async () => {
    await area.locator("blockquote").first().hover()
    await area.locator("[data-drag-handle]").first().click()
    await page.getByRole("menuitem", { name: "删除", exact: true }).click()
    await page.getByRole("dialog", { name: "删除内容块？", exact: true }).waitFor()
  }
  const dialog = page.getByRole("dialog", { name: "删除内容块？", exact: true })
  for (const method of ["button", "escape", "backdrop"]) {
    await openDelete()
    assert.equal(await dialog.getByRole("button", { name: "取消", exact: true }).evaluate(e => document.activeElement === e), true)
    await page.keyboard.press("Tab")
    assert.equal(await dialog.getByRole("button", { name: "确认删除", exact: true }).evaluate(e => document.activeElement === e), true)
    if (method === "button") await dialog.getByRole("button", { name: "取消", exact: true }).click()
    else if (method === "escape") await page.keyboard.press("Escape")
    else await page.locator(".hn-block-delete-backdrop").click({ position: { x: 2, y: 2 } })
    assert.deepEqual(await doc(), initial)
  }
  await openDelete()
  await page.screenshot({ animations: "disabled", path: `${dir}/delete-confirm.png` })
  await dialog.getByRole("button", { name: "确认删除", exact: true }).click()
  assert.equal((await doc()).content.length, 1)
  await page.keyboard.press("Control+z")
  assert.deepEqual(await doc(), initial)
  await page.keyboard.press("Control+Shift+Z")
  assert.equal((await doc()).content.length, 1)
  evidence.S3 = await doc()
  console.log("PASS S3: cancel/Escape/backdrop, focus/Tab, whole subtree delete and exact undo/redo")
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await load([p("正文")])
    await select(0)
    await page.keyboard.type("/")
    const menu = page.getByRole("listbox", { name: "转换当前行" })
    await menu.waitFor()
    assert.equal(await menu.getByRole("option").count(), 9)
    assert.equal(await page.getByRole("toolbar", { name: "文字与块操作", exact: true }).isVisible(), false)
    const palette = await menu.evaluate(e => ({ bg: getComputedStyle(e).backgroundColor, text: getComputedStyle(e.querySelector("button:not(:disabled)")).color }))
    assert.equal(palette.bg, "rgb(255, 255, 255)")
    assert.equal(palette.text, "rgb(30, 41, 59)")
    const box = await menu.boundingBox()
    assert(box.x >= 0 && box.x + box.width <= width && box.y >= 0 && box.y + box.height <= 1000)
    await page.keyboard.press("ArrowDown")
    await page.screenshot({ animations: "disabled", path: `${dir}/slash-${width}.png` })
    await page.keyboard.press("Enter")
    const result = await doc()
    assert.equal(result.content[0].type, "heading")
    assert.equal(result.content[0].attrs.level, 2)
    assert.equal(await area.evaluate(e => e.editor.state.doc.textContent), "正文")
    await page.keyboard.press("Control+z")
    assert.equal(await area.evaluate(e => e.editor.state.doc.textContent), "/正文")
    await page.keyboard.press("Control+Shift+Z")
    assert.deepEqual(await doc(), result)
    await load([p("a")]); await select(1); await page.keyboard.type("/")
    assert.equal(await menu.count(), 0)
    await load([p("正文")]); await select(0); await page.keyboard.type("/"); await page.keyboard.press("Escape")
    assert.equal(await area.evaluate(e => e.editor.state.doc.textContent), "/正文")
  }
  evidence.S5 = await doc()
  console.log("PASS S5: 1440/390px slash keyboard selection, bounds, cancellation, inline exclusion, exact undo/redo")
  await load([p("history")])
  await select(0); await page.keyboard.type("X")
  const withText = await doc()
  for (const mod of ["Control", "Meta"]) {
    await page.keyboard.press(`${mod}+z`)
    assert.equal(await area.evaluate(e => e.editor.state.doc.textContent), "history")
    await page.keyboard.press(`${mod}+Shift+Z`)
    assert.deepEqual(await doc(), withText)
  }
  console.log("PASS S6 automated keyboard: Ctrl and Meta undo/redo; physical macOS and Windows NOT covered")
  writeFileSync(`${dir}/browser-hnn.json`, JSON.stringify(evidence, null, 2))
  assert.deepEqual(errors, [])
  console.log("S4 is verified separately by check-pane-toolbar-browser.mjs (1440/390px and mixed themes).")
} finally { await browser.close() }
