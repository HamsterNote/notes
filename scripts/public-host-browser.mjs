import assert from "node:assert/strict"

export async function checkPublicHost(page, url, prefix = "evidence/ham49-public-host") {
  const errors = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.route("**/image.png?*", (route) => route.fulfill({ contentType: "image/png", body: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aN5sAAAAASUVORK5CYII=", "base64") }))
  await page.goto(url)
  const a = page.locator('[data-view-id="a"]'), b = page.locator('[data-view-id="b"]')
  await a.locator(".tiptap").waitFor()
  const status = async (view, kind, expected) => {
    await page.waitForFunction(({ view, kind, expected }) => document.querySelector(`[data-view-id="${view}"] [data-hnn-node="${kind}"]`)?.getAttribute("data-hnn-resolve-status") === expected, { view, kind, expected })
  }
  for (const view of ["a", "b"]) await status(view, "mention", "resolved")
  await a.locator(".tiptap > p").first().click()
  await page.keyboard.press("Control+Home"); await page.keyboard.type("edit ")
  // Let ordinary autosave settle before comparing state across reference refreshes.
  await page.waitForFunction(() => {
    const statuses = [...document.querySelectorAll(".hn-editor-controls [role=status]")]
    return statuses.length === 2 && statuses.every((element) => element.textContent === "已保存")
  })
  await page.getByRole("button", { name: "Snapshot", exact: true }).click()
  const before = JSON.parse(await page.locator("[data-result]").textContent())
  const changes = await page.evaluate(() => localStorage.getItem("changes"))
  const calls = await page.evaluate(() => Number(localStorage.getItem("resolve-calls")))
  await page.getByRole("button", { name: "Invalidate Candidate", exact: true }).click()
  for (const view of ["a", "b"]) { await status(view, "mention", "missing"); await status(view, "resource", "resolved") }
  assert.equal(await page.evaluate(() => Number(localStorage.getItem("resolve-calls"))), calls + 2)
  await page.getByRole("button", { name: "Invalidate Document", exact: true }).click()
  for (const view of ["a", "b"]) await status(view, "resource", "missing")
  await page.getByRole("button", { name: "Snapshot", exact: true }).click()
  assert.deepEqual(JSON.parse(await page.locator("[data-result]").textContent()), before)
  assert.equal(await page.evaluate(() => localStorage.getItem("changes")), changes)
  await b.getByLabel("撤销", { exact: true }).click()
  assert.equal(await a.locator(".tiptap > p").first().textContent(), "body @HighlightHighlight")
  await a.getByLabel("重做", { exact: true }).click()
  assert((await b.locator(".tiptap > p").first().textContent()).startsWith("edit body"))
  console.log("PASS reference candidate/document invalidation, both views, same session/state, shared history")
  const input = a.locator('input[type="file"]')
  const enqueue = async (name) => input.setInputFiles({ name, mimeType: "image/png", buffer: Buffer.from("image") })
  await enqueue("success.png")
  await page.getByRole("button", { name: "Freeze", exact: true }).click()
  await page.waitForFunction(() => JSON.parse(document.querySelector("[data-result]").textContent).reason === "pending-edit")
  await a.getByRole("button", { name: "保存", exact: true }).click()
  await page.waitForFunction(() => localStorage.getItem("saved") !== null)
  assert(!JSON.stringify(await page.evaluate(() => JSON.parse(localStorage.getItem("saved")))).match(/uploadId|attempt|success\.png/))
  await page.getByRole("button", { name: "Resolve Upload", exact: true }).click()
  await a.locator('img[src*="success.png"]').waitFor()
  await b.locator('img[src*="success.png"]').waitFor()
  assert.equal(await a.locator('img[src*="success.png"]').count(), 1)
  assert.equal(await a.locator('img[src*="success.png"]').evaluate((img) => img.complete && img.naturalWidth > 0), true)
  await b.getByLabel("撤销", { exact: true }).click()
  assert.equal(await a.locator('img[src*="success.png"]').count(), 0)
  await a.getByLabel("重做", { exact: true }).click()
  await a.locator('img[src*="success.png"]').waitFor()
  await enqueue("retry.png")
  await page.getByRole("button", { name: "Reject Upload", exact: true }).click()
  await a.getByRole("button", { name: "重试上传 retry.png", exact: true }).click()
  const log = await page.evaluate(() => JSON.parse(localStorage.getItem("upload-log")))
  assert.equal(log.at(-1).uploadId, log.at(-2).uploadId)
  assert.equal(log.at(-1).attempt, 2)
  await a.getByRole("button", { name: "取消上传 retry.png", exact: true }).click()
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem("upload-log")))).at(-1).aborted, true)
  await page.getByRole("button", { name: "Resolve Upload", exact: true }).click()
  await page.getByRole("button", { name: "Snapshot", exact: true }).click()
  assert.equal(await page.locator('img[src*="retry.png"]').count(), 0)
  console.log("PASS upload success/shared undo, failure/retry identity, cancel/abort/late, save/freeze pending")
  for (const kind of ["卡片", "画板"]) {
    await enqueue(`${kind === "卡片" ? "card" : "drawing"}.png`)
    await a.getByLabel(`编辑${kind}`, { exact: true }).click()
    await page.getByRole("dialog").waitFor()
    // A host callback can finish behind the modal; no synthetic editor commands are used.
    await page.evaluate(() => [...document.querySelectorAll(".fixture-toolbar button")].find((button) => button.textContent === "Resolve Upload").click())
    assert.equal(await a.locator(`img[src*="${kind === "卡片" ? "card" : "drawing"}.png"]`).count(), 0)
    await page.getByRole("dialog").getByRole("button", { name: "取消", exact: true }).click()
    await a.locator(`img[src*="${kind === "卡片" ? "card" : "drawing"}.png"]`).waitFor()
  }
  await enqueue("detach.png")
  await page.getByLabel("Left View", { exact: true }).uncheck()
  await page.getByRole("button", { name: "Resolve Upload", exact: true }).click()
  await page.getByLabel("Left View", { exact: true }).check()
  assert.equal(await page.locator('img[src*="detach.png"]').count(), 0)
  await enqueue("remove.png")
  await page.getByLabel("Upload Enabled", { exact: true }).uncheck()
  await page.getByRole("button", { name: "Resolve Upload", exact: true }).click()
  await page.getByLabel("Upload Enabled", { exact: true }).check()
  assert.equal(await page.locator('img[src*="remove.png"]').count(), 0)
  await page.getByRole("button", { name: "Freeze", exact: true }).click()
  await page.waitForFunction(() => JSON.parse(document.querySelector("[data-result]").textContent).action === "acquired")
  assert.equal(await a.getByRole("button", { name: "插入图片", exact: true }).isDisabled(), true)
  await page.getByRole("button", { name: "Invalidate Document", exact: true }).click()
  await status("a", "mention", "missing")
  await page.getByRole("button", { name: "Freeze", exact: true }).click()
  await a.getByRole("button", { name: "保存", exact: true }).click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("saved")).document.data.content.filter((node) => node.type === "picture").length === 3)
  await page.screenshot({ path: `${prefix}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: `${prefix}-mobile.png`, fullPage: true })
  assert.deepEqual(errors, [])
  console.log("PASS card/drawing deferred commits, detach/remove late isolation, frozen refresh, persisted HNN, desktop/mobile")
}
