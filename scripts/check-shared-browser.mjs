import assert from "node:assert/strict"
import { mkdirSync } from "node:fs"
import { chromium } from "playwright"
import { createServer } from "vite"

mkdirSync("evidence", { recursive: true })
const server = await createServer({ configFile: "vite.demo.config.ts", server: { port: 0, host: "127.0.0.1" } })
await server.listen()
const browser = await chromium.launch({ headless: true })
try {
  console.log("browser", browser.version())
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto(`${server.resolvedUrls.local[0]}shared.html`)
  const a = page.locator('[data-view-id="a"] .tiptap')
  const b = page.locator('[data-view-id="b"] .tiptap')
  await a.waitFor()
  const para = (view) => view.locator("p").first()
  const text = async (expected) => {
    console.log("actual", await para(a).textContent(), await para(b).textContent(), "errors", errors)
    await page.screenshot({ path: "evidence/browser-current.png", fullPage: true })
    await page.waitForFunction((value) => [...document.querySelectorAll(".tiptap > p:first-of-type")].every((node) => node.textContent === value), expected, { timeout: 5000 })
    assert.equal(await para(a).textContent(), expected)
    assert.equal(await para(b).textContent(), expected)
    console.log("body", expected)
  }
  await para(a).click(); await page.keyboard.press("Control+Home"); await page.keyboard.type("AA")
  await para(b).click(); await page.keyboard.press("Control+Home")
  await page.waitForFunction(() => { const s = getSelection(); return s?.anchorNode?.parentElement === document.querySelector('[data-view-id="b"] .tiptap > p') && s.anchorOffset === 0 })
  console.log("selection-before-right", await page.evaluate(() => { const s = getSelection(); return { anchor: s?.anchorNode?.parentElement?.outerHTML, offset: s?.anchorOffset } }))
  await page.keyboard.press("ArrowRight")
  await page.waitForFunction(() => { const s = getSelection(); return s?.anchorNode?.parentElement === document.querySelector('[data-view-id="b"] .tiptap > p') && s.anchorOffset === 1 })
  console.log("selection-after-arrow", await page.evaluate(() => { const s = getSelection(); return { anchor: s?.anchorNode?.parentElement?.outerHTML, offset: s?.anchorOffset } }))
  await page.keyboard.type("B")
  await text("ABA共享正文")
  await para(a).click(); await page.keyboard.press("Control+z"); await text("AA共享正文")
  await page.getByLabel("撤销", { exact: true }).nth(1).click(); await text("共享正文")
  await page.getByLabel("重做", { exact: true }).first().click()
  await page.getByLabel("重做", { exact: true }).nth(1).click(); await text("ABA共享正文")
  await page.getByLabel("左栏", { exact: true }).uncheck()
  await page.getByLabel("左栏", { exact: true }).check()
  await text("ABA共享正文")
  await page.getByLabel("锁定输入", { exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll(".tiptap")].every((node) => node.getAttribute("contenteditable") === "false"))
  assert.equal(await page.getByLabel("笔记标题").isDisabled(), true)
  await page.getByLabel("锁定输入", { exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll(".tiptap")].every((node) => node.getAttribute("contenteditable") === "true"))
  await a.getByLabel("编辑卡片", { exact: true }).click()
  const dialog = page.getByRole("dialog")
  await dialog.waitFor()
  assert.equal(await page.getByLabel("撤销", { exact: true }).first().isDisabled(), true)
  await dialog.getByRole("button", { name: "添加卡片", exact: true }).click()
  await dialog.getByRole("button", { name: "完成", exact: true }).click()
  await dialog.waitFor({ state: "hidden" })
  await page.getByRole("button", { name: "保存笔记", exact: true }).click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("notes-shared-demo") ?? "null")?.document.data.content[0].content[0].text === "ABA共享正文")
  await page.screenshot({ path: "evidence/shared-desktop.png", fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: "evidence/shared-mobile.png", fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  assert.deepEqual(errors, [])
  console.log("PASS: native interleaving, keyboard/toolbar undo-redo, reopen, freeze, draft, save, responsive layout")
  console.log("NOT RUN: physical IME and WebBase host bridge")
} finally {
  await browser.close()
  await server.close()
}
